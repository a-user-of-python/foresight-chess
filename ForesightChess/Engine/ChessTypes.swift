// ChessTypes.swift
// Adaptive Chess — core value types for the chess engine.
//
// Board coordinates: file 0-7 = a-h, rank 0-7 = 1-8.
// (rank 0 is White's back rank, rank 7 is Black's back rank.)

import Foundation

// MARK: - PieceColor

/// The two sides in a game of chess.
public enum PieceColor: String, Codable, CaseIterable {
    case white
    case black

    /// The opposing color.
    public var opposite: PieceColor {
        self == .white ? .black : .white
    }
}

// MARK: - PieceType

/// The six kinds of chess pieces.
public enum PieceType: String, Codable, CaseIterable {
    case pawn
    case knight
    case bishop
    case rook
    case queen
    case king

    /// Lowercase FEN letter for this piece type.
    var fenLetter: Character {
        switch self {
        case .pawn:   return "p"
        case .knight: return "n"
        case .bishop: return "b"
        case .rook:   return "r"
        case .queen:  return "q"
        case .king:   return "k"
        }
    }

    /// Parse a FEN piece letter (either case) into a piece type.
    static func fromFENLetter(_ ch: Character) -> PieceType? {
        switch ch.lowercased() {
        case "p": return .pawn
        case "n": return .knight
        case "b": return .bishop
        case "r": return .rook
        case "q": return .queen
        case "k": return .king
        default:  return nil
        }
    }

    /// Lowercase UCI promotion letter ("q", "r", "b", "n").
    var uciPromotionLetter: String {
        switch self {
        case .queen:  return "q"
        case .rook:   return "r"
        case .bishop: return "b"
        case .knight: return "n"
        case .pawn, .king: return ""
        }
    }
}

// MARK: - Piece

/// A chess piece: a type plus the color that owns it.
public struct Piece: Equatable, Hashable, Codable {
    public let type: PieceType
    public let color: PieceColor

    public init(type: PieceType, color: PieceColor) {
        self.type = type
        self.color = color
    }

    /// FEN character: uppercase for White, lowercase for Black.
    var fenChar: Character {
        let lower = type.fenLetter
        return color == .white ? Character(lower.uppercased()) : lower
    }

    /// Unicode glyph for board rendering (white pieces outlined, black filled).
    public var glyph: String {
        switch (type, color) {
        case (.king, .white):   return "♔"
        case (.queen, .white):  return "♕"
        case (.rook, .white):   return "♖"
        case (.bishop, .white): return "♗"
        case (.knight, .white): return "♘"
        case (.pawn, .white):   return "♙"
        case (.king, .black):   return "♚"
        case (.queen, .black):  return "♛"
        case (.rook, .black):   return "♜"
        case (.bishop, .black): return "♝"
        case (.knight, .black): return "♞"
        case (.pawn, .black):   return "♟"
        }
    }
}

// MARK: - Square

/// A board square. `file` 0-7 maps to a-h, `rank` 0-7 maps to 1-8.
public struct Square: Equatable, Hashable, Codable {
    public let file: Int
    public let rank: Int

    public init(file: Int, rank: Int) {
        self.file = file
        self.rank = rank
    }

    /// True when both coordinates are on the 8x8 board.
    public var isValid: Bool {
        Square.isValid(file: file, rank: rank)
    }

    public static func isValid(file: Int, rank: Int) -> Bool {
        file >= 0 && file < 8 && rank >= 0 && rank < 8
    }

    /// Algebraic notation, e.g. "e4". file 0 = "a", rank 0 = "1".
    public var algebraic: String {
        let f = Character(UnicodeScalar(97 + file)!)
        return "\(f)\(rank + 1)"
    }

    /// Parse algebraic notation like "e4". Returns nil for invalid input.
    public init?(algebraic: String) {
        guard algebraic.count == 2 else { return nil }
        let chars = Array(algebraic.lowercased())
        guard let fileScalar = chars[0].unicodeScalars.first,
              let rankValue = Int(String(chars[1])) else { return nil }
        let file = Int(fileScalar.value) - 97
        let rank = rankValue - 1
        guard Square.isValid(file: file, rank: rank) else { return nil }
        self.init(file: file, rank: rank)
    }

    /// Offset by (df, dr). Returns nil when the result is off the board.
    func offsetBy(file df: Int, rank dr: Int) -> Square? {
        let f = file + df, r = rank + dr
        guard Square.isValid(file: f, rank: r) else { return nil }
        return Square(file: f, rank: r)
    }
}

// MARK: - GameResult

/// The outcome of a finished game.
public enum GameResult: String, Codable {
    case whiteWins
    case blackWins
    case draw
}

// MARK: - Move

/// A chess move, as generated by `ChessGame.legalMoves()`.
///
/// The `from`/`to`/`promotion` fields identify the move. The boolean flags
/// describe special move kinds so `makeMove` can apply them correctly.
/// Moves are only ever constructed by the engine — callers must pass moves
/// obtained from `legalMoves()` back into `makeMove(_:)`.
public struct Move: Equatable, Hashable {
    public let from: Square
    public let to: Square
    /// Non-nil only for pawn promotions (queen/rook/bishop/knight).
    public let promotion: PieceType?
    public let isCapture: Bool
    public let isCastleKingside: Bool
    public let isCastleQueenside: Bool
    public let isEnPassant: Bool

    public init(from: Square,
                to: Square,
                promotion: PieceType? = nil,
                isCapture: Bool = false,
                isCastleKingside: Bool = false,
                isCastleQueenside: Bool = false,
                isEnPassant: Bool = false) {
        self.from = from
        self.to = to
        self.promotion = promotion
        self.isCapture = isCapture
        self.isCastleKingside = isCastleKingside
        self.isCastleQueenside = isCastleQueenside
        self.isEnPassant = isEnPassant
    }

    /// UCI-style string, e.g. "e2e4" or "e7e8q". Handy for debugging and logs.
    public var uci: String {
        var s = from.algebraic + to.algebraic
        if let p = promotion { s += p.uciPromotionLetter }
        return s
    }

    /// Destination square in algebraic notation, e.g. "e4".
    /// Useful for building simple opening keys ("e4 e5 ...").
    public var destinationAlgebraic: String {
        to.algebraic
    }
}
